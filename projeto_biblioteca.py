import json

ARQUIVO_DADOS = "livros.json"
livros = []

def carregar_acervo_exemplo():
    return [
        {"titulo": "Dom Casmurro", "autor": "Machado de Assis", "ano": 1899, "disponivel": True},
        {"titulo": "O Alquimista", "autor": "Paulo Coelho", "ano": 1988, "disponivel": False},
        {"titulo": "Harry Potter e a Pedra Filosofal", "autor": "J.K. Rowling", "ano": 1997, "disponivel": True},
        {"titulo": "1984", "autor": "George Orwell", "ano": 1949, "disponivel": True},
        {"titulo": "O Pequeno Príncipe", "autor": "Antoine de Saint-Exupéry", "ano": 1943, "disponivel": False},
        {"titulo": "Memórias Póstumas de Brás Cubas", "autor": "Machado de Assis", "ano": 1881, "disponivel": True},
        {"titulo": "A Hora da Estrela", "autor": "Clarice Lispector", "ano": 1977, "disponivel": True},
        {"titulo": "Vidas Secas", "autor": "Graciliano Ramos", "ano": 1938, "disponivel": False},
        {"titulo": "O Senhor dos Anéis", "autor": "J.R.R. Tolkien", "ano": 1954, "disponivel": True},
        {"titulo": "A Revolução dos Bichos", "autor": "George Orwell", "ano": 1945, "disponivel": True}
    ]

def verificar_acervo_vazio():
    if not livros:
        print("⚠️ Nenhum livro cadastrado!")
        return True
    return False

def exibir_cabecalho(titulo):
    largura = 55
    print("\n" + "=" * largura)
    print(f"{titulo:^{largura}}")
    print("=" * largura)

def carregar_dados():
    global livros
    try:
        with open(ARQUIVO_DADOS, "r", encoding="utf-8") as arquivo:
            livros = json.load(arquivo)
        print(f"✅ {len(livros)} livro(s) carregado(s)!")
    except (FileNotFoundError, json.JSONDecodeError):
        print("📄 Criando acervo de exemplo...")
        livros = carregar_acervo_exemplo()
        salvar_dados()
        print(f"✅ {len(livros)} livro(s) de exemplo carregado(s)!")
    if not livros:
        print("🔄 Recarregando acervo...")
        livros = carregar_acervo_exemplo()
        salvar_dados()

def salvar_dados():
    try:
        with open(ARQUIVO_DADOS, "w", encoding="utf-8") as arquivo:
            json.dump(livros, arquivo, ensure_ascii=False, indent=4)
        return True
    except Exception as erro:
        print(f"❌ Erro ao salvar: {erro}")
        return False

def ler_indice(mensagem, limite):
    try:
        numero = int(input(mensagem))
        indice = numero - 1
        if 0 <= indice < limite:
            return indice
        print("⚠️ Número fora do intervalo!")
    except ValueError:
        print("⚠️ Digite apenas números!")
    return None

def confirmar_acao(pergunta):
    resposta = input(f"{pergunta} (S/N): ").strip().lower()
    return resposta == "s"

def exibir_status(disponivel):
    return "✅ Disponível" if disponivel else "❌ Emprestado"

def exibir_contador():
    total = len(livros)
    disponiveis = sum(1 for livro in livros if livro["disponivel"])
    emprestados = total - disponiveis
    print(f"\n📊 Total: {total} | ✅ Disponíveis: {disponiveis} | ❌ Emprestados: {emprestados}")
    print("-" * 40)

def cadastrar_livro():
    exibir_cabecalho("CADASTRO DE LIVRO")
    while True:
        titulo = input("Título: ").strip()
        if titulo: break
        print("⚠️ Título obrigatório!")
    while True:
        autor = input("Autor: ").strip()
        if autor: break
        print("⚠️ Autor obrigatório!")
    while True:
        try:
            ano = int(input("Ano: ").strip())
            if 1000 < ano <= 2100: break
            print("⚠️ Ano entre 1001 e 2100!")
        except ValueError:
            print("⚠️ Digite apenas números!")
    livro = {"titulo": titulo, "autor": autor, "ano": ano, "disponivel": True}
    livros.append(livro)
    if salvar_dados():
        print(f"✅ '{titulo}' cadastrado!")

def listar_livros():
    exibir_cabecalho("LISTA DE LIVROS")
    if verificar_acervo_vazio(): return
    print("Ordenar: 1-Título | 2-Ano | ENTER=padrão")
    opcao = input("Escolha: ").strip()
    lista = livros.copy()
    if opcao == "1":
        lista.sort(key=lambda l: l["titulo"].lower())
    elif opcao == "2":
        lista.sort(key=lambda l: l["ano"], reverse=True)
    elif opcao:
        print("ℹ️ Opção inválida — ordem de cadastro.")
    exibir_contador()
    for i, livro in enumerate(lista, 1):
        print(f"\n{i}. {livro['titulo']}")
        print(f"   Autor: {livro['autor']} | Ano: {livro['ano']}")
        print(f"   Status: {exibir_status(livro['disponivel'])}")
    print("\n" + "=" * 55)

def buscar_livro():
    exibir_cabecalho("BUSCAR LIVRO")
    print(f"ℹ️ Acervo com {len(livros)} livros")
    termo = input("Digite título ou autor: ").strip().lower()
    if not termo:
        print("⚠️ Digite algo!")
        return
    encontrados = [
        livro for livro in livros
        if termo in livro["titulo"].lower() or termo in livro["autor"].lower()
    ]
    print("\n" + "=" * 55)
    if encontrados:
        print(f"✅ {len(encontrados)} resultado(s):")
        for i, livro in enumerate(encontrados, 1):
            print(f"{i}. {livro['titulo']} — {livro['autor']}")
            print(f"   {exibir_status(livro['disponivel'])}")
    else:
        print(f"❌ Nenhum resultado para '{termo}'.")
    print("=" * 55)

def realizar_emprestimo():
    exibir_cabecalho("EMPRÉSTIMO")
    if verificar_acervo_vazio(): return
    for i, livro in enumerate(livros, 1):
        if livro["disponivel"]:
            print(f"{i}. {livro['titulo']} — {livro['autor']}")
    indice = ler_indice("Número: ", len(livros))
    if indice is None: return
    livro = livros[indice]
    if not livro["disponivel"]:
        print(f"❌ Já emprestado!")
        return
    livro["disponivel"] = False
    if salvar_dados():
        print(f"✅ Empréstimo de '{livro['titulo']}'!")

def realizar_devolucao():
    exibir_cabecalho("DEVOLUÇÃO")
    if verificar_acervo_vazio(): return
    tem_emprestados = False
    for i, livro in enumerate(livros, 1):
        if not livro["disponivel"]:
            print(f"{i}. {livro['titulo']} — {livro['autor']}")
            tem_emprestados = True
    if not tem_emprestados:
        print("📚 Nenhum para devolver!")
        return
    indice = ler_indice("Número: ", len(livros))
    if indice is None: return
    livro = livros[indice]
    if livro["disponivel"]:
        print(f"❌ Já disponível!")
        return
    livro["disponivel"] = True
    if salvar_dados():
        print(f"✅ '{livro['titulo']}' devolvido!")

def remover_livro():
    exibir_cabecalho("REMOÇÃO")
    if verificar_acervo_vazio(): return
    for i, livro in enumerate(livros, 1):
        print(f"{i}. {livro['titulo']} — {livro['autor']}")
    indice = ler_indice("Número: ", len(livros))
    if indice is None: return
    livro = livros[indice]
    if not confirmar_acao(f"Remover '{livro['titulo']}'?"):
        print("❌ Cancelado.")
        return
    livros.pop(indice)
    if salvar_dados():
        print(f"✅ Removido!")

def menu():
    carregar_dados()
    while True:
        print("\n" + "=" * 35)
        print("   SISTEMA DE BIBLIOTECA")
        print("=" * 35)
        print("1. Cadastrar  |  2. Listar  |  3. Buscar")
        print("4. Empréstimo |  5. Devolução |  6. Remover")
        print("7. Sair")
        print("=" * 35)
        opcao = input("Escolha: ")
        if opcao == "1": cadastrar_livro()
        elif opcao == "2": listar_livros()
        elif opcao == "3": buscar_livro()
        elif opcao == "4": realizar_emprestimo()
        elif opcao == "5": realizar_devolucao()
        elif opcao == "6": remover_livro()
        elif opcao == "7":
            print("👋 Até logo!")
            break
        else:
            print("⚠️ Opção inválida!")

if __name__ == "__main__":
    menu()